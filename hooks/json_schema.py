"""MkDocs hook: publish the DDAML JSON Schema as ``schema.json`` at the site root.

The file is generated in memory on every build (including ``mkdocs serve``), so
it never needs to be committed or generated by hand, and links to it resolve in
strict builds.
"""

from data_model.json_schema import schema_json
from mkdocs.config.defaults import MkDocsConfig
from mkdocs.structure.files import File, Files


def on_files(files: Files, config: MkDocsConfig) -> Files:
    existing = files.get_file_from_path("schema.json")
    if existing is not None:
        # A stale docs/schema.json from an older workflow; the generated one wins.
        files.remove(existing)
    files.append(File.generated(config, "schema.json", content=schema_json()))
    return files
